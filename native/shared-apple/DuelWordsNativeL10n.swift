import Foundation

/// App-local localization for the Swift surfaces embedded by React Native.
///
/// These surfaces must follow DuelWords' explicit interface language instead of
/// the device language, so Bundle.main/LocalizedStringKey are not sufficient.
struct DuelWordsNativeL10n {
    static let supportedLanguageCodes = ["en", "es", "ca", "fr", "de"]

    let languageCode: String

    init(interfaceLocale: String) {
        let normalized = interfaceLocale.lowercased().split(separator: "-").first.map(String.init) ?? "en"
        languageCode = Self.supportedLanguageCodes.contains(normalized) ? normalized : "en"
    }

    var locale: Locale {
        Locale(identifier: languageCode)
    }

    func text(_ english: String) -> String {
        Self.translations[languageCode]?[english] ?? english
    }

    func markdown(_ english: String) -> AttributedString {
        let localized = text(english)
        return (try? AttributedString(markdown: localized)) ?? AttributedString(localized)
    }

